PHASE5_BASELINE_VERSION_VAR = "phase5-baseline-v1"


def regime_map(all_trades) -> Dict[str, SliceStats]:
    m: Dict[str, List] = {}
    for t in all_trades:
        m.setdefault(t.regime, []).append(t)
    return {k: slice_stats(v, len(v), k) for k, v in m.items()}


def chronological_slices_for(d: DatasetData):
    trades = sorted(d.trades, key=lambda t: t.entry_ts)
    if not trades:
        return []
    total = len(trades)
    n = 4
    per = max(1, total // n)
    out = []
    for i in range(0, total, per):
        group = trades[i : i + per]
        if not group:
            continue
        st = slice_stats(group, len(group), f"p{i//per}")
        out.append(
            {
                "period": i // per,
                "n": len(group),
                "start_ts": int(group[0].entry_ts),
                "end_ts": int(group[-1].exit_ts),
                "avg_return": st.avg_return,
                "win_rate": st.win_rate,
                "profit_factor": st.profit_factor,
                "expectancy": st.expectancy,
            }
        )
    return out